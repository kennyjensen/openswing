import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test.use({launchOptions:{executablePath:process.env.OPENSWING_CHROMIUM_EXECUTABLE,
  args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--disable-webgl','--js-flags=--max-old-space-size=192']}});

test('real SA-11 worker rejection shows diagnostic geometry, export, mobile layout and clears on edit',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#panels').fill('12');await page.locator('#panels').press('Tab');
  await page.locator('#example').selectOption('isae-sa11-wingtip-up');
  await expect(page.locator('#model-name')).toHaveText('SA-11 · Upper winglets');
  await page.locator('#mode').selectOption('rigid');
  await page.locator('#speed').fill('240');await page.locator('#speed').press('Tab');
  await page.locator('#alpha').fill('1');await page.locator('#alpha').press('Tab');
  await page.locator('#solve').click();
  await expect(page.locator('#flow-failure')).toBeVisible();
  await expect(page.locator('#flow-failure')).toContainText('No accepted solution');
  await expect(page.locator('#flow-failure')).toContainText('frozen jig');
  await expect(page.locator('#cl')).toHaveText('—');
  await expect(page.locator('#csv')).toBeDisabled();
  await page.locator('#close-error').click();
  await page.locator('#top-view').click();
  const withMarkers=await page.locator('#viewport canvas').screenshot();
  await page.locator('#flow-failure-toggle').click();
  await expect(page.locator('#flow-failure-toggle')).toHaveAttribute('aria-pressed','false');
  expect(Buffer.compare(withMarkers,await page.locator('#viewport canvas').screenshot())).not.toBe(0);
  await page.locator('#flow-failure-toggle').click();
  expect(Buffer.compare(withMarkers,await page.locator('#viewport canvas').screenshot())).toBe(0);
  const downloading=page.waitForEvent('download');await page.locator('#flow-failure-download').click();
  const download=await downloading,filename=info.outputPath('rejected-airflow.json');await download.saveAs(filename);
  const saved=JSON.parse(await readFile(filename,'utf8'));
  expect(saved.format).toBe('openswing-rejected-airflow');
  expect(saved.error).toContain('Local section-normal Mach');
  expect(saved.details.kind).toBe('section_normal_mach');
  expect(saved.details.maximum.normal_mach).toBeGreaterThanOrEqual(1);
  const sections=saved.details.rejected_sections;
  expect(sections.length).toBeGreaterThan(1);
  expect(sections.every(s=>s.normal_mach>=1&&s.position.every(Number.isFinite))).toBeTruthy();
  expect(sections[0].normal_mach).toBe(saved.details.maximum.normal_mach);
  await expect(page.locator('#flow-failure')).toContainText(`${sections.length} rejected sections`);
  expect(saved.details.circulation_residual).toBeLessThan(1e-8);
  expect(saved.request.condition.speed).toBe(240);expect(saved.request.condition.alpha).toBe(1);
  expect(saved.software_provenance.fingerprint).toMatch(/^[0-9a-f]{64}$/);
  const forces=saved.details.surface_force_diagnostic;
  expect(forces.available).toBe(true);expect(forces.validity).toBe('rejected-state diagnostic');
  expect(forces.pitching_moment_available).toBe(false);
  expect(forces.rejected_strips).toBe(sections.length);
  expect(forces.beams).toHaveLength(3);
  expect(forces.terms.sum.CL).toBeGreaterThan(0);expect(forces.terms.sum.CD).toBeGreaterThan(0);
  const scale=forces.normalization.dynamic_pressure*forces.normalization.reference_area;
  const projected=forces.terms.sum.force_body.reduce((sum,v,i)=>sum+v*forces.axes.lift[i],0)/scale;
  expect(projected).toBeCloseTo(forces.terms.sum.CL,12);
  await expect(page.locator('#flow-failure-forces')).toContainText('Pitching moment is unavailable');
  await expect(page.locator('#flow-failure-forces')).toContainText('Excludes apparent mass, bodies, point-object drag and engines');
  await expect(page.locator('#flow-failure-forces tbody tr')).toHaveCount(8);
  await expect(page.locator('#flow-failure-forces tbody tr').first()).toContainText(forces.terms.sum.CL.toPrecision(5));
  await expect(page.locator('#flow-failure-forces tbody tr').first()).toContainText(forces.terms.sum.CD.toPrecision(5));
  await expect(page.locator('#export-json')).toBeDisabled();
  await expect(page.locator('#equilibrium-use')).toBeDisabled();
  expect(saved.result).toBeUndefined();expect(saved.equilibrium_state).toBeUndefined();
  await page.locator('#flow-failure-sections summary').click();
  await expect(page.locator('#flow-failure-sections tbody tr')).toHaveCount(sections.length);
  await page.locator('#flow-failure-sources summary').click();
  await expect(page.locator('#flow-failure-sources tbody tr')).toHaveCount(6);
  await page.screenshot({path:info.outputPath('desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('tab',{name:'Plots',exact:true}).click();
  await expect(page.locator('#flow-failure')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  expect(await page.evaluate(()=>document.querySelector('#viewport').getBoundingClientRect().bottom<=document.querySelector('#flow-failure').getBoundingClientRect().top)).toBeTruthy();
  await page.screenshot({path:info.outputPath('mobile.png'),fullPage:true});
  await page.getByRole('tab',{name:'Settings',exact:true}).click();
  await page.locator('#alpha').fill('2');await page.locator('#alpha').press('Tab');
  await page.getByRole('tab',{name:'Plots',exact:true}).click();
  await expect(page.locator('#flow-failure')).toBeHidden();
  await page.getByRole('tab',{name:'Settings',exact:true}).click();
  await page.locator('#speed').fill('30');await page.locator('#speed').press('Tab');
  await page.locator('#solve').click();
  await expect(page.locator('#runtime-status')).toContainText('Analysis converged');
  await expect(page.locator('#flow-failure')).toBeHidden();
  await expect(page.locator('#error')).toBeHidden();
  await expect(page.locator('#cl')).not.toHaveText('—');
  await expect(page.locator('#csv')).toBeEnabled();
  expect(errors).toEqual([]);
});
