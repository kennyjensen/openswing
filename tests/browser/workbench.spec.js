test('browser worker advances coupled free-flight time states locally', async ({ page,context }) => {
  await page.addInitScript(()=>{
    const NativeWorker=window.Worker;
    window.Worker=class extends NativeWorker {constructor(...args){super(...args);window.physicsWorker=this;}};
  });
  await page.goto('/');
  await expect(page.locator('#solve')).toBeEnabled();
  const source=await readFile('examples/inertial.asw','utf8');
  await context.setOffline(true);
  const result=await page.evaluate(source=>new Promise((resolve,reject)=>{
    const id=-100;
    const receive=({data})=>{
      if(data.id!==id||data.type)return;
      window.physicsWorker.removeEventListener('message',receive);
      if(data.error)reject(new Error(data.error));else resolve(data.result);
    };
    window.physicsWorker.addEventListener('message',receive);
    window.physicsWorker.postMessage({id,request:{action:'time',source,panels:4,
      condition:{alpha:5,mach:0},time:{duration:.02,dt:.01,frame:'free'}}});
  }),source);
  expect(result.analysis).toBe('time_response');expect(result.accepted_steps).toBe(2);
  expect(result.snapshots).toHaveLength(3);
  expect(result.snapshots.at(-1).residual).toBeLessThan(1e-8);
  expect(result.snapshots.at(-1).frame.position_earth[0]).toBeLessThan(-.5);
  expect(Math.max(...result.snapshots.at(-1).circulation_rate.map(Math.abs))).toBeGreaterThan(1);
  expect(result.snapshots[0].frame.position_earth).toEqual([0,0,0]);
});

test('loaded WebAssembly app solves and exports locally with networking disabled', async ({ page,context }) => {
  const requests=[];
  context.on('request',request=>requests.push({url:request.url(),method:request.method()}));
  await page.addInitScript(()=>{
    const NativeWorker=window.Worker;window.kernelReplies=0;
    window.Worker=class extends NativeWorker {
      constructor(...args){super(...args);this.addEventListener('message',event=>{if(event.data.id)window.kernelReplies++;});}
    };
  });
  await page.goto('/');
  await expect(page.locator('#solve')).toBeEnabled();
  // The initial parse has loaded the complete numerical runtime into its worker.
  await context.setOffline(true);
  await page.locator('#mode').selectOption('mounted');
  // Change a flight input before the pending mesh inspection can reply.
  await page.evaluate(()=>{
    document.querySelector('#panels').value='4';document.querySelector('#panels').dispatchEvent(new Event('change',{bubbles:true}));
    document.querySelector('#alpha').value='5';document.querySelector('#alpha').dispatchEvent(new Event('input',{bubbles:true}));
    const flap=document.querySelector('[data-control="1"]');flap.value='3';flap.dispatchEvent(new Event('input',{bubbles:true}));
  });
  await page.locator('#solve').click();
  await expect(page.locator('#result-state')).toHaveText('Converged · mounted equilibrium');
  const download=page.waitForEvent('download');await page.locator('#export-json').click();
  const result=JSON.parse(await readFile(await (await download).path(),'utf8'));
  expect(result.converged).toBe(true);expect(result.residual).toBeLessThan(1e-8);
  expect(result.CL).toBeGreaterThan(.3);expect(result.CL).toBeLessThan(.6);
  expect(result.structural_nodes).toBeGreaterThan(0);
  await expect(page.locator('[data-control="1"]')).toHaveValue('3');
  const beforeMesh=await page.evaluate(()=>window.kernelReplies);
  await page.evaluate(()=>{
    document.querySelector('#panels').value='8';document.querySelector('#panels').dispatchEvent(new Event('change',{bubbles:true}));
    document.querySelector('#panels').value='12';document.querySelector('#panels').dispatchEvent(new Event('input',{bubbles:true}));
  });
  await expect.poll(()=>page.evaluate(()=>window.kernelReplies)).toBeGreaterThan(beforeMesh);
  await expect(page.locator('#solve')).toBeDisabled();
  await expect(page.locator('#runtime-status')).toContainText('Apply the new mesh');
  // Editing source must still invalidate an older inspection reply.
  const before=await page.evaluate(()=>window.kernelReplies);
  await page.evaluate(()=>{
    document.querySelector('#panels').value='8';document.querySelector('#panels').dispatchEvent(new Event('change',{bubbles:true}));
    document.querySelector('#editor').value='Name\nUnapplied source';document.querySelector('#editor').dispatchEvent(new Event('input',{bubbles:true}));
  });
  await expect.poll(()=>page.evaluate(()=>window.kernelReplies)).toBeGreaterThan(before);
  await expect(page.locator('#solve')).toBeDisabled();
  await expect(page.locator('#editor')).toHaveValue('Name\nUnapplied source');
  await expect(page.locator('#runtime-status')).toContainText('Editor changed');
  expect(requests.length).toBeGreaterThan(10);
  for(const request of requests){
    expect(new URL(request.url).origin).toBe(new URL(page.url()).origin);
    expect(request.method).toBe('GET');
  }
});

