  await expect(page.locator('#cdi')).toHaveText(out.snapshots.at(-1).CDi.toFixed(5));
  await expect(page.locator('#cdi-near')).toHaveText(out.snapshots.at(-1).CDi_near.toFixed(5));
  await expect(page.locator('#trefftz-note')).toContainText('frozen straight wake');
  await expect(page.locator('#time-current')).toContainText('0.040000');
  await page.locator('#time-view').selectOption('earth');
  await expect(page.locator('#geometry-label')).toContainText('EARTH FRAME');
  await page.locator('#tab-loading').click();if(!(await page.locator('#plot-quantity').inputValue()).startsWith('structure:'))await page.locator('#plot-quantity').selectOption('structure:shell.axial_strain_bound');
  await expect(page.locator('#plot svg')).toBeVisible();
  dl=page.waitForEvent('download');await page.locator('#csv').click();
  const sections=await readFile(await (await dl).path(),'utf8');
  expect(sections).toContain('"time [input T]"');expect(sections).toContain('"0.04"');
  await page.locator('#tab-loading').click();await page.locator('#plot-quantity').selectOption('fz');await page.locator('#plot-scope').selectOption('overlay');
  await expect(page.locator('#plot .distribution-trace')).toHaveCount(out.snapshots.length);
