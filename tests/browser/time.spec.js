  await page.locator('#time-quantity').selectOption('node.displacement.2');
  await expect(page.locator('#time-node')).toBeVisible();
  await page.locator('#time-quantity').selectOption('frame.position_earth.2');
  await page.locator('#time-play-speed').selectOption('0.1');
  await page.locator('#time-play').click();
  await expect(page.locator('#time-play')).toHaveText('Pause');
  await expect(page.locator('#time-play')).toHaveText('Play');
  await expect(page.locator('#time-scrub')).toHaveValue(String(out.snapshots.length-1));
  await page.screenshot({path:'test-results/time-workbench.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.locator('#pane-time').scrollIntoViewIfNeeded();
  await expect.poll(()=>page.locator('#time-plot').evaluate(el=>Math.abs(el.querySelector('svg').viewBox.baseVal.width-el.clientWidth))).toBeLessThan(1);
