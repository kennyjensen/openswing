  dl=page.waitForEvent('download');await page.locator('#time-csv').click();
  expect(await readFile(await(await dl).path(),'utf8')).toContain(String(out.snapshots.at(-1).CDi));
  await page.locator('#time-quantity').selectOption('forcing_values.F1');
  dl=page.waitForEvent('download');await page.locator('#time-csv').click();
