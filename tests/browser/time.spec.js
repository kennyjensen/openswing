  await page.locator('#forcing-file').setInputFiles({name:'maneuver.txt',mimeType:'text/plain',buffer:Buffer.from(forcing)});
  await expect(page.locator('#time-forcing')).toHaveValue(forcing);
  const saved=page.waitForEvent('download');await page.locator('#forcing-save').click();
  expect(await readFile(await (await saved).path(),'utf8')).toBe(forcing);
  await context.setOffline(true);
  await page.locator('#solve').click();
  await expect(page.locator('#time-transport')).toBeVisible({timeout:120000});
  await expect(page.locator('#runtime-status')).toHaveText('Time integration converged');
  await expect(page.locator('#tab-time')).toHaveAttribute('aria-selected','true');
  await expect(page.locator('#time-plot svg')).toBeVisible();
  let dl=page.waitForEvent('download');await page.locator('#export-json').click();
  const out=JSON.parse(await readFile(await (await dl).path(),'utf8'));
  expect(out.analysis).toBe('time_response');expect(out.request.time.forcing).toBe(forcing);
  expect(out.request.source).toContain('Inertial reference wing');
  expect(out.snapshots.at(-1).time).toBe(.04);
  const event=out.snapshots.findIndex(s=>s.time===.015);
