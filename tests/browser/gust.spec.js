import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('Earth gust fields preview, round trip and drive steady/time loads offline',async({page,context})=>{
  test.setTimeout(180000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#panels').fill('4');await page.locator('#panels').press('Tab');
  await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#alpha').fill('0');await page.locator('#speed').fill('10');
  await page.locator('#gust-settings').evaluate(e=>e.open=true);
  await page.locator('#gust-kind').selectOption('cosine');
  await page.locator('#gust-preview-settings').evaluate(e=>e.open=true);
  await page.locator('#gust-preview').click();
  await expect(page.locator('#gust-plot svg')).toBeVisible();
  await expect(page.locator('#gust-preview-note')).toContainText('0.0000 to 1.0000');
  const pulse={type:'cosine',amplitude:[0,0,1],origin:[-3,0,0],normal:[-1,0,0],length:3,speed:0};
  let download=page.waitForEvent('download');await page.locator('#gust-save').click();
  expect(JSON.parse(await readFile(await(await download).path(),'utf8'))).toEqual(pulse);
  const file=spec=>({name:'field.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(spec))});
  await page.locator('#gust-file').setInputFiles(file({type:'uniform',velocity:[5,0,0]}));
  await expect(page.locator('#gust-kind')).toHaveValue('custom');
  await context.setOffline(true);
  await page.locator('#solve').click();await expect(page.locator('#runtime-status')).toHaveText('Analysis converged');
  await expect(page.locator('#cdp')).toHaveText('0.01800');
  await page.locator('#tab-report').click();
  await expect(page.locator('#pane-report')).toContainText('EARTH GUST · uniform');
  await expect(page.locator('#pane-report')).toContainText('no additional ambient-pressure-gradient term');
  download=page.waitForEvent('download');await page.locator('#export-json').click();
  let out=JSON.parse(await readFile(await(await download).path(),'utf8'));
  expect(out.gust.reference_velocity_body).toEqual([5,0,0]);
  expect(out.atmosphere.dynamic_pressure).toBeCloseTo(61.25,6);
  await page.locator('#gust-component').selectOption('0');
  await page.locator('#gust-preview').click();await expect(page.locator('#gust-plot svg')).toBeVisible();
  await expect(page.locator('#export-json')).toBeEnabled();
  await page.locator('#gust-xmin').fill('');
  await page.locator('#solve').click();await expect(page.locator('#runtime-status')).toHaveText('Analysis converged');
  await expect(page.locator('#error')).toBeHidden();
  await page.locator('#gust-xmin').fill('-15');
  await page.locator('#gust-kind').selectOption('expression');
  await expect(page.locator('#export-json')).toBeDisabled();
  await page.locator('#gust-expr-z').fill('0.05*t');
  await page.locator('#mode').selectOption('time');
  await page.locator('#time-duration').fill('.04');await page.locator('#time-step').fill('.01');
  await page.locator('#solve').click();await expect(page.locator('#runtime-status')).toHaveText('Time integration converged');
  await page.locator('#time-quantity').selectOption('gust.reference_velocity_body.2');
  await expect(page.locator('#time-plot svg')).toBeVisible();
  download=page.waitForEvent('download');await page.locator('#export-json').click();
  out=JSON.parse(await readFile(await(await download).path(),'utf8'));
  expect(out.request.condition.gust.components).toEqual(['0','0','0.05*t']);
  expect(out.snapshots.at(-1).CL).toBeGreaterThan(0);
  for(const s of out.snapshots){expect(s.gust.time).toBe(s.time);expect(s.gust.reference_velocity_body[2]).toBeCloseTo(.05*s.time,10);expect(s.residual).toBeLessThan(1e-8);expect(s.limitations.join(' ')).toContain('Sears');}
  await page.locator('#time-scrub').evaluate((e,n)=>{e.value=n;e.dispatchEvent(new Event('input',{bubbles:true}));},out.snapshots.length-1);
  await page.locator('#tab-report').click();await expect(page.locator('#pane-report')).toContainText('Field time [T] 0.04');
  await page.locator('#gust-kind').selectOption('cosine');
  await page.locator('#gust-component').selectOption('2');
  await page.locator('#gust-preview').click();await expect(page.locator('#gust-plot svg')).toBeVisible();
  await page.locator('#gust-settings').screenshot({path:'test-results/gust-field.png'});
  await page.screenshot({path:'test-results/gust-workbench.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.screenshot({path:'test-results/gust-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});

test('gust editor reports unsupported catalog and unsafe expressions without stale results',async({page})=>{
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#gust-settings').evaluate(e=>e.open=true);
  await page.locator('#gust-file').setInputFiles({name:'legacy.gust',mimeType:'text/plain',buffer:Buffer.from('8\n-3\n0\n3\n1\n0\n')});
  await expect(page.locator('#error')).toContainText('gust type 8 has no verified parameter map');
  await page.locator('#close-error').click();
  await page.locator('#gust-kind').selectOption('expression');
  await page.locator('#gust-expr-z').fill('__import__("os")');
  await page.locator('#solve').click();
  await expect(page.locator('#error')).toContainText('Unsupported gust expression');
  await expect(page.locator('#export-json')).toBeDisabled();
  await expect(page.locator('#solve')).toBeEnabled();
});
