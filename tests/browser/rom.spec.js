import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
async function downloadJson(page,id){const event=page.waitForEvent('download');await page.locator(id).click();return JSON.parse(await readFile(await(await event).path(),'utf8'));}

test('selected-mode ROM runs offline, retains acceleration feedthrough and exports immutable matrices',async({page,context})=>{
  test.setTimeout(300000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#example').selectOption('instrumented-oscillator');
  await expect(page.locator('#model-name')).toHaveText('Instrumented spring-mass demonstrator');
  await page.locator('#panels').fill('4');await page.locator('#panels').press('Tab');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#speed').fill('10');await page.locator('#alpha').fill('0');
  await page.locator('#atmosphere-settings').evaluate(e=>e.open=true);
  await page.locator('#gravity-mode').selectOption('custom');await page.locator('#gravity-magnitude').fill('0');
  await page.locator('#mach-mode').selectOption('fixed');await page.locator('#pg-mach').fill('0');
  await page.locator('#mode').selectOption('modes');await page.locator('#modal-count').fill('2');
  await context.setOffline(true);await page.locator('#solve').click();
  await expect(page.locator('#runtime-status')).toHaveText('Analysis converged',{timeout:180000});
  const modes=await downloadJson(page,'#export-json');
  await page.locator('#rom-settings').evaluate(e=>e.open=true);
  await page.locator('#rom-modes').selectOption('0');
  await page.locator('#rom-outputs').fill('RY[2], UY[2], Ay[2]');
  await page.locator('#rom-initial-settings').evaluate(e=>e.open=true);
  const initialProfiles=JSON.parse(await readFile('examples/initial-spring.json','utf8'));
  await page.locator('#rom-initial-file').setInputFiles({name:'initial.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(initialProfiles))});
  await expect(page.locator('#rom-initial-import-note')).toContainText('Imported physical profiles');
  expect(await downloadJson(page,'#rom-initial-save')).toEqual(initialProfiles);
  await page.locator('#rom-initial-times').fill('0, 0.1, 0.2, 0.5');
  await page.locator('#rom-frequencies').fill('0, 10, 50');await page.locator('#rom-build').click();
  await expect(page.locator('#runtime-status')).toHaveText('Reduced model generated',{timeout:180000});
  await expect(page.locator('#rom-summary')).toContainText('2 real states');
  const result=await downloadJson(page,'#rom-json');
  expect(result.format).toBe('openswing-rom');expect(result.matrices.A).toHaveLength(2);
  expect(result.diagnostics.retained[0].conjugate_source_index).toBeNull();
  expect(result.matrices.D[2][0]).toBeCloseTo(.5,7);
  expect(result.samples[0].reduced.real[0][0]).toBeCloseTo(.002,8);
  for(const row of result.diagnostics.maximum_normalized_transfer_errors)expect(row[0]).toBeLessThan(1e-6);
  expect(result.initial_responses).toHaveLength(2);
  for(const [i,profile] of result.initial_responses.entries()){
    expect(profile.converged).toBeTruthy();expect(profile.projection.relative_dynamic_norm).toBeLessThan(1e-7);
    const q0=i===0?.002:0,v0=i===1?.01:0,wd=Math.sqrt(243.75);
    for(const sample of profile.time_samples){
      const t=sample.time,c=Math.cos(wd*t),s=Math.sin(wd*t),decay=Math.exp(-2.5*t);
      const q=decay*(q0*c+(v0+2.5*q0)/wd*s),v=decay*(v0*c-(250*q0+2.5*v0)/wd*s);
      for(const key of ['full','reduced'])for(const [j,value] of [q,v,-250*q-5*v].entries())expect(sample[key][j]).toBeCloseTo(value,7);
    }
  }
  await expect(page.locator('#rom-initial-plot svg')).toBeVisible();
  await expect(page.locator('#rom-initial-table tbody tr')).toHaveCount(4);
  await page.locator('#rom-initial-output').selectOption('2');
  await expect(page.locator('#rom-initial-unit')).toContainText('input L/T^2 / profile amplitude');
  await page.locator('#rom-initial-results').screenshot({path:'test-results/rom-initial-history.png'});
  await page.locator('#rom-initial-profile').selectOption('1');await page.locator('#rom-initial-display').selectOption('spectrum');
  await expect(page.locator('#rom-initial-unit')).toContainText('input L/T^2 · input T');
  await expect(page.locator('#rom-initial-table tbody tr')).toHaveCount(3);
  expect(result.initial_responses[1].samples[0].full.real[2]).toBeCloseTo(-.01,8);
  const initialCsvEvent=page.waitForEvent('download');await page.locator('#rom-initial-csv').click();
  const initialCsv=await readFile(await(await initialCsvEvent).path(),'utf8');expect(initialCsv).toContain('initial spectrum');expect(initialCsv).toContain('input L/T^2 · input T');
  await page.locator('#rom-initial-results').screenshot({path:'test-results/rom-initial-spectrum.png'});
  expect(await downloadJson(page,'#rom-json')).toEqual(result);
  await page.locator('#rom-output').selectOption('2');await expect(page.locator('#rom-plot svg')).toBeVisible();
  await expect(page.locator('#rom-unit')).toContainText('input L/T^2 / file engine setting');
  await expect(page.locator('#rom-comparison tbody tr')).toHaveCount(3);
  const event=page.waitForEvent('download');await page.locator('#rom-text').click();
  const text=await readFile(await(await event).path(),'utf8');expect(text).toBe(result.text_export);expect(text).toContain('D_rate 3 1');expect(text).toContain('# initial_conditions ');
  await page.locator('#modal-phase').fill('90');expect(await downloadJson(page,'#rom-json')).toEqual(result);
  expect(await downloadJson(page,'#export-json')).toEqual(modes);
  await page.locator('#rom-settings').screenshot({path:'test-results/rom-results.png'});
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.locator('#rom-settings').screenshot({path:'test-results/rom-mobile.png'});
  await expect(page.locator('#rom-legacy')).toBeEnabled();
  const legacyEvent=page.waitForEvent('download');await page.locator('#rom-legacy').click();
  const legacy=await readFile(await(await legacyEvent).path(),'utf8');expect(legacy).toBe(result.legacy_export);
  await page.locator('#tab-romfiles').click();await page.locator('#romfile-file').setInputFiles({name:'generated.rom',mimeType:'text/plain',buffer:Buffer.from(legacy)});
  await expect(page.locator('#romfile-summary')).toContainText('2 real states');
  const imported=await downloadJson(page,'#romfile-json');expect(imported.model.inputs[0].name).toBe('Peng_01');
  expect(imported.samples[0].response.real[0][0]).toBeCloseTo(.002,8);
  expect(imported.real_matrices.D[2][0]).toBeCloseTo(.5,7);
  expect(await downloadJson(page,'#export-json')).toEqual(modes);await page.locator('#tab-modes').click();
  await page.locator('#rom-frequencies').fill('1, 3, 20');await expect(page.locator('#rom-json')).toBeDisabled();
  expect(await downloadJson(page,'#export-json')).toEqual(modes);
  await page.locator('#rom-inputs').selectOption([]);await page.locator('#rom-build').click();
  await expect(page.locator('#runtime-status')).toHaveText('Reduced model generated',{timeout:180000});
  await expect(page.locator('#rom-summary')).toContainText('free response only');
  await expect(page.locator('#rom-unit')).toContainText('No periodic inputs');
  await expect(page.locator('#rom-initial-plot svg')).toBeVisible();
  const freeOnly=await downloadJson(page,'#rom-json');expect(freeOnly.inputs).toEqual([]);expect(freeOnly.matrices.B).toEqual([[],[]]);
  expect(freeOnly.initial_responses.every(p=>p.converged)).toBeTruthy();
  expect(await downloadJson(page,'#export-json')).toEqual(modes);
  expect(errors).toEqual([]);
});

test('ROM includes controller command inputs and preserves the lag dynamics',async({page,context})=>{
  test.setTimeout(300000);
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#example').selectOption('instrumented-oscillator');
  await expect(page.locator('#model-name')).toHaveText('Instrumented spring-mass demonstrator');
  await page.locator('#panels').fill('4');await page.locator('#panels').press('Tab');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#speed').fill('10');await page.locator('#alpha').fill('0');
  await page.locator('#atmosphere-settings').evaluate(e=>e.open=true);
  await page.locator('#gravity-mode').selectOption('custom');await page.locator('#gravity-magnitude').fill('0');
  await page.locator('#mach-mode').selectOption('fixed');await page.locator('#pg-mach').fill('0');
  await page.locator('#mode').selectOption('modes');await page.locator('#modal-count').fill('3');
  await page.locator('#feedback-settings').evaluate(e=>e.open=true);await page.locator('#feedback-lag-demo').click();
  await context.setOffline(true);await page.locator('#solve').click();
  await expect(page.locator('#runtime-status')).toHaveText('Analysis converged',{timeout:180000});
  await page.locator('#rom-settings').evaluate(e=>e.open=true);
  await page.locator('#rom-modes').selectOption(['0','1','2']);
  await page.locator('#rom-inputs').selectOption([{label:'Engine 1'},{label:'Command RY[2]'}]);
  await page.locator('#rom-outputs').fill('RY[2], Ay[2]');await page.locator('#rom-frequencies').fill('0, 10');
  await page.locator('#rom-build').click();await expect(page.locator('#runtime-status')).toHaveText('Reduced model generated',{timeout:180000});
  const result=await downloadJson(page,'#rom-json');expect(result.matrices.A).toHaveLength(3);
  expect(result.inputs.map(x=>x.name)).toEqual(['power.1','command.RY[2]']);
  expect(result.samples[0].reduced.real[0][1]).toBeCloseTo(2/7,7);
  expect(result.controller.state_channels).toEqual(['lag']);
  await page.locator('#rom-input').selectOption('1');await expect(page.locator('#rom-unit')).toContainText('input L / input L');
  await page.locator('#rom-settings').screenshot({path:'test-results/rom-controller.png'});
  await page.locator('#feedback-enabled').uncheck();await expect(page.locator('#rom-json')).toBeDisabled();await expect(page.locator('#rom-build')).toBeDisabled();
});
