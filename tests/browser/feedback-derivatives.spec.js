import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('closed-loop steady derivatives solve offline and export physical controller response',async({page,context})=>{
  test.setTimeout(240000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#file').setInputFiles('examples/instrumented-oscillator.asw');
  await page.locator('#panels').fill('4');await page.locator('#panels').press('Tab');await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#mode').selectOption('mounted');await page.locator('#alpha').fill('0');await page.locator('#speed').fill('10');
  await page.locator('#atmosphere-settings').evaluate(e=>e.open=true);
  await page.locator('#gravity-mode').selectOption('custom');await page.locator('#gravity-magnitude').fill('0');
  await page.locator('#feedback-settings').evaluate(e=>e.open=true);
  await page.locator('#feedback-definition').fill(JSON.stringify({commands:{'RY[2]':2.01},outputs:[{actuator:'E1',terms:[{input:'RY[2]',gain:-200},{input:'RY[2]',gain:-100,mode:'integral'}]}]}));
  await page.locator('#feedback-enabled').check();
  await page.locator('#derivative-settings').evaluate(e=>e.open=true);await page.locator('#derivatives-enable').check();
  await expect(page.locator('#derivative-parameters input[value="power.1"]')).toHaveCount(0);
  const bias=page.locator('#derivative-parameters input[value="command.E1"]');await expect(bias).toBeChecked();
  for(const input of await page.locator('#derivative-parameters input').all())await input.setChecked(['command.E1','command.RY[2]'].includes(await input.inputValue()));
  await context.setOffline(true);await page.locator('#solve').click();
  await expect(page.locator('#runtime-status')).toHaveText('Analysis converged',{timeout:120000});
  await page.locator('#tab-derivatives').click();await page.locator('#derivative-matrix').selectOption('feedback');
  await expect(page.locator('#derivative-note')).toContainText('Closed-loop equilibrium');
  await expect(page.locator('#derivative-table')).toContainText('integrals.RY[2]');
  await expect(page.locator('#derivative-plot svg')).toBeVisible();
  let event=page.waitForEvent('download');await page.locator('#export-json').click();
  const result=JSON.parse(await readFile(await(await event).path(),'utf8')),d=result.derivatives;
  expect(d.parameters.map(p=>p.name)).toEqual(['command.E1','command.RY[2]']);
  const row=name=>d.matrices.feedback[d.feedback_rows.findIndex(row=>row.name===name)];
  expect(row('actuators.E1')[0]).toBeCloseTo(0,7);expect(row('actuators.E1')[1]).toBeCloseTo(500,5);
  expect(row('integrals.RY[2]')[0]).toBeCloseTo(.01,7);expect(row('integrals.RY[2]')[1]).toBeCloseTo(-5,6);
  expect(d.controller.commands['RY[2]']).toBe(2.01);
  event=page.waitForEvent('download');await page.locator('#derivative-csv').click();
  const csv=await readFile(await(await event).path(),'utf8');expect(csv).toContain('integrals.RY[2] [input L · input T]');expect(csv).toContain('command.E1 / file engine setting');
  await page.screenshot({path:'test-results/feedback-derivatives-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.locator('#pane-derivatives').scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:'test-results/feedback-derivatives-mobile.png'});
  await page.locator('#feedback-enabled').uncheck();await expect(page.locator('#derivative-csv')).toBeDisabled();
  await expect(page.locator('#derivative-parameters input[value="power.1"]')).toBeChecked();
  await expect(page.locator('#derivative-parameters input[value="command.E1"]')).toHaveCount(0);
  expect(errors).toEqual([]);
});
