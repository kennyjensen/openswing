def model():
    return parse_asw((BASE/'source/examples/inertial.asw').read_text()+'''\nEngine
1 0 1 0 0 0 0 1 0 0 1 0 -1 0 0
2 0 1 0 0 0 0 0 0 1 0 1 -1 0 0
End
''')


def rows(quantity, target=2., variable='control.1'):
    return [dict(variable=variable, quantity=quantity, target=target)]


def forcing(text, quantity=None, target=2., variable='control.1', **kwargs):
    m = model()
    c = FlightCondition(controls={1: 3}, powers={1: .25, 2: .5})
    return TimeForcing(text, m, c, c.motion(), 20., 'free',
        actuator_constraints=None if quantity is None else rows(quantity, target, variable), **kwargs)


def rotate(attitude):
    """Independently written expanded ASW matrix, no production pose helper."""
    p, t, h = [math.radians(v) for v in attitude]
    cp, sp, ct, st, ch, sh = math.cos(p), math.sin(p), math.cos(t), math.sin(t), math.cos(h), math.sin(h)
    return np.array([[ch*ct, sh*cp-ch*st*sp, sh*sp+ch*st*cp],
                     [-sh*ct, ch*cp+sh*st*sp, ch*sp-sh*st*cp],
                     [-st, -ct*sp, ct*cp]])


def evaluator(quantity, condition, target=0., *, marked=True, m=None):
    m = model() if m is None else m
    constraint = (TimeHistoryConstraint if marked else OperatingConstraint)('control.1', quantity, target)
    return OperatingSystem(m, condition, condition.motion(), [constraint], 2., 100.)


@pytest.mark.parametrize('label,quantity,factor,order', EXPECTED)
def test_all_audited_labels_units_relative_offsets_and_canonical_serialization(label, quantity, factor, order):
    f = forcing(f'time +{label.swapcase()}\n* 2 3\n+ 0 5\n0 1\n1 3', quantity, target=2*factor)
    # Physical t=2q; data y=5+3(1+2q), plus independent initial table value 2.
    assert f.values(.6) == pytest.approx({label: 11.8})
    assert f.targets(.6) == pytest.approx({quantity: 11.8*factor})
    assert f.targets(.6, derivative=1) == pytest.approx({quantity: 3*factor})
    assert f.targets(.6, derivative=2) == {quantity: 0.}
    metadata = history_channel(label)
    assert metadata.quantity == quantity and metadata.factor == pytest.approx(factor)
    assert metadata.derivative_order == order
    assert f.report()['channels'][0]['inverse_history'] == asdict(metadata)
    saved = time_constraint_data(time_operating_constraints('free', actuator_constraints=rows(quantity, 2*factor)))
    restored = time_operating_constraints('free', **json.loads(json.dumps(saved)))
    assert isinstance(restored[-1], TimeHistoryConstraint)
    assert asdict(restored[-1]) == asdict(OperatingConstraint('control.1', quantity, 2*factor))
    # Saved controller command binding must not overwrite the inverse target's offset.
    f.bind_commands({label: 99})
    assert f.targets(.6) == pytest.approx({quantity: 11.8*factor})


