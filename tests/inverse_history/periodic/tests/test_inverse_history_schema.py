def test_actual_trial_state_mapping_reference_offsets_density_gust_and_controller_distinction():
    m = model()
    m.reference[2] = [2., -1., .5]
    m.reference[3] = [.7, -.4, .2]
    base = FlightCondition(speed=19., alpha=0., density=m.constants[1]/4,
        acceleration=(.3, -.5, .7), angular_acceleration=(.02, .04, -.06),
        gust={'type':'expression', 'components':['1+.1*x+.2*t', '-.7+.05*y', '.3-.08*z']})
    network = SimpleNamespace(model=m, condition=base, motion=base.motion(), gravity_override=True, gravity=np.zeros(3))
    system = object.__new__(TimeSystem)
    system.network, system.V, system.feedback, system.forcing = network, 20., None, None
    for U, omega, pose, p, t in [([-17,2,-3],[.1,-.2,.3],[21,-14,35],[4,5,6],.4),
                                 ([-23,-1,4],[-.2,.15,.08],[-16,24,-39],[-3,2,1],.9)]:
        R = rotate(pose)
        U, omega, p = np.array(U), np.array(omega), np.array(p)
        state = SimpleNamespace(U=U, Omega=omega, position=p, orientation=R, time=t)
        c, motion = system.condition(state)
        point = p+R@np.array(m.reference[3])
        gust = np.array([1+.1*point[0]+.2*t, -.7+.05*point[1], .3-.08*point[2]])
        still = -U-np.cross(omega, m.reference[3])
        relative = still+R.T@gust
        speed = np.linalg.norm(relative)
        ve = R@(U+np.cross(omega, m.reference[3]))
        expected = {'reference.equivalent_airspeed':speed/2,
            'reference.alpha':math.degrees(math.atan2(relative[2],relative[0])),
            'reference.beta':math.degrees(math.atan2(-relative[1],math.hypot(relative[0],relative[2]))),
            'flight_path':math.degrees(math.atan2(ve[2],math.hypot(ve[0],ve[1])))}
        for group, vector in [('rates',omega), ('position_earth',p), ('velocity_earth',ve),
            ('rates_earth',R@omega), ('acceleration_earth',R@np.array(base.acceleration)),
            ('angular_acceleration_earth',R@np.array(base.angular_acceleration))]:
            expected.update({group+'.'+axis:float(value) for axis,value in zip('xyz',vector)})
        expected.update({'attitude.'+axis:value for axis,value in zip(('bank','elevation','heading'),pose)})
        data = {'reference_flow':reference_airflow(m,c), 'earth_state':c.earth_state(m), 'condition':c, 'motion':motion}
        np.testing.assert_allclose(data['reference_flow']['relative_velocity_body'], relative, atol=1e-13)
        for _, quantity, _, _ in EXPECTED:
            op = evaluator(quantity, base, target=10. if quantity=='reference.equivalent_airspeed' else 0., m=m)
            residual, report = op.evaluate(np.zeros(3),np.zeros(3),data,c,motion=motion,targets={quantity:expected[quantity]})
            assert report[0]['actual'] == pytest.approx(expected[quantity], rel=2e-13, abs=2e-13)
            assert residual[0] == pytest.approx(0., abs=2e-13)
        controller_values = measurements(network,state,data)
        assert controller_values['V'] == pytest.approx(np.linalg.norm(still))
        assert controller_values['V'] != pytest.approx(expected['reference.equivalent_airspeed'])
        assert controller_values['A'] == pytest.approx(math.degrees(math.atan2(still[2],still[0])))
        assert controller_values['A'] != pytest.approx(expected['reference.alpha'])
        assert controller_values['B'] == pytest.approx(math.degrees(math.atan2(-still[1],math.hypot(still[0],still[2]))))
        assert controller_values['B'] != pytest.approx(expected['reference.beta'])
        np.testing.assert_allclose([controller_values[k] for k in ('UX','UY','UZ')],R@U)
        assert not np.allclose(R@U,ve)


@pytest.mark.parametrize('quantity', ['reference.alpha','attitude.bank','attitude.heading'])
def test_periodic_local_residual_and_antipodal_or_stencil_cut_rejection(quantity):
    assert history_error(quantity, -179., 179.) == 2.
    assert history_error(quantity, 179., -179.) == -2.
    assert history_error(quantity, -178., 179., anchor_error=2.) == 3.
    with pytest.raises(ValueError, match='antipodal'):
        history_error(quantity, 0., 180.)
    with pytest.raises(ValueError, match='branch cut'):
        history_error(quantity, -179., 0., anchor_error=179.)
    c = FlightCondition(alpha=-179, attitude=(-179,0,-179))
    data = {'reference_flow':reference_airflow(model(),c), 'earth_state':c.earth_state(model())}
    op = evaluator(quantity,c,target=179)
    assert op.evaluate([0,0,0],[0,0,0],data,c)[0][0] == pytest.approx(.2)
    steady = evaluator(quantity,c,target=179,marked=False)
    # Existing steady alpha was already periodic; steady Euler residuals stay linear.
    expected = .2 if quantity=='reference.alpha' else -35.8
    assert steady.evaluate([0,0,0],[0,0,0],data,c)[0][0] == pytest.approx(expected)


