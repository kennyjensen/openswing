@pytest.mark.parametrize('quantity', ['reference.alpha','attitude.bank','attitude.heading'])
def test_matched_later_half_turn_uses_current_target_not_obsolete_homotopy_origin(quantity):
    m = model()
    start = FlightCondition(alpha=0.,attitude=(0.,0.,0.))
    op = evaluator(quantity,start)
    initial = {'reference_flow':reference_airflow(m,start)}
    assert op.evaluate([0,0,0],[0,0,0],initial,start)[0] == [0.]
    later = replace(start,alpha=180.,attitude=(180.,0.,180.))
    data = {'reference_flow':reference_airflow(m,later)}
    assert op.evaluate([0,0,0],[0,0,0],data,later,targets={quantity:180.})[0] == pytest.approx([0.],abs=1e-13)
    # A fractional continuation path still requires a chosen initial branch.
    with pytest.raises(ValueError,match='antipodal'):
        op.evaluate([0,0,0],[0,0,0],data,later,factor=.5,targets={quantity:180.})


