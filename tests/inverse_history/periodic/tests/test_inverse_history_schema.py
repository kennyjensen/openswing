def test_achieved_flow_and_euler_singularities_are_scoped_to_time_inverse_rows():
    m = model()
    lateral = FlightCondition(speed=10.,alpha=0.,beta=90.)
    data = {'reference_flow':reference_airflow(m,lateral)}
    assert data['reference_flow']['beta'] == 90.
    with pytest.raises(ValueError, match='singular at a lateral'):
        evaluator('reference.beta',lateral).evaluate([0,0,0],[0,0,0],data,lateral)
    # Historical steady beta endpoints remain accepted and finite.
    assert evaluator('reference.beta',lateral,target=90.,marked=False).evaluate([0,0,0],[0,0,0],data,lateral)[0] == [0.]
    cancelled = FlightCondition(speed=10.,alpha=0.,gust={'type':'uniform','velocity':[-10,0,0]})
    with pytest.raises(ValueError, match='zero or cancelled'):
        evaluator('reference.equivalent_airspeed',cancelled,target=1.).evaluate(
            [0,0,0],[0,0,0],{'reference_flow':reference_airflow(m,cancelled)},cancelled)
    for quantity in ['attitude.bank','attitude.elevation','attitude.heading']:
        pole = FlightCondition(attitude=(12.,90.,23.))
        with pytest.raises(ValueError, match='Euler-angle chart'):
            evaluator(quantity,pole).evaluate([0,0,0],[0,0,0],{},pole)
        # Ordinary steady rows retain their original numeric chart behavior.
        assert math.isfinite(evaluator(quantity,pole,marked=False).evaluate([0,0,0],[0,0,0],{},pole)[0][0])
    vertical = FlightCondition(alpha=90.)
    with pytest.raises(ValueError, match='nonzero, nonvertical'):
        evaluator('flight_path',vertical).evaluate([0,0,0],[0,0,0],{'earth_state':vertical.earth_state(m)},vertical)


def test_stencil_adapter_accepts_actual_time_options_signature_and_keeps_branch_local():
    f = forcing('time RX\n1 2\n2 4\n2 10\n3 16','position_earth.x',start_time=1.)
    c = FlightCondition(speed=10.,alpha=0.,controls={1:3})
    m = model()
    system = object.__new__(TimeSystem)
    system.network = SimpleNamespace(model=m,condition=c,motion=c.motion(),gravity_override=True,gravity=np.zeros(3))
    system.V, system.feedback = 10., None
    state = SimpleNamespace(U=np.array([-10.,0,0]),Omega=np.zeros(3),position=np.zeros(3),
        orientation=np.eye(3),time=.9,u=np.zeros((1,3)),w=np.zeros((1,3)),feedback=np.empty(0))
    z = np.zeros((1,3))
    system.forcing = f.stencil_forcing(1.,'right')
    out = system.options(state,z,z,np.empty(0),'left')
    assert out['operating_targets'] == pytest.approx({'position_earth.x':1.8})
    np.testing.assert_array_equal(out['condition_override'].position_earth,[0,0,0])
    assert out['condition_override'].controls == {1:3}
    for anchor_side, expected in [('left',4.2),('right',10.6)]:
        system.forcing = f.stencil_forcing(2.,anchor_side)
        state.time=2.1
        for query_side in ['left','right']:
            assert system.options(state,z,z,np.empty(0),query_side)['operating_targets'] == pytest.approx({'position_earth.x':expected})
    system.forcing = f.stencil_forcing(3.,'right')
    state.time=2.9
    assert system.options(state,z,z,np.empty(0),'left')['operating_targets'] == {'position_earth.x':0.}
    assert not hasattr(system.forcing,'events')
    assert system.forcing.report()['physical_lookup'] is False
    # Physical table behavior has neither prehistory nor a changed endpoint rule.
    with pytest.raises(AnalysisError,match='before the first'):
        f.targets(.9)
    assert f.targets(3.,'right') == {'position_earth.x':16.}
    assert f.targets(3.1) == {'position_earth.x':0.}
    with pytest.raises(AnalysisError,match='left/right'):
        system.forcing.targets(2.9,'unknown')
