@pytest.mark.parametrize('direct,variable', [('F1', 'control.1'), ('E1', 'power.1')])
def test_actuator_output_has_one_owner_even_without_any_forcing_column(direct, variable):
    with pytest.raises(ValueError, match='solved actuator'):
        forcing(f'time {direct}\n0 0\n1 1', 'velocity_earth.x', variable=variable)
    m, c = model(), FlightCondition()
    control = FeedbackSystem(SimpleNamespace(model=m, condition=c),
        {'outputs': [{'actuator': direct, 'terms': [{'input':'V', 'gain':1}]}]})
    with pytest.raises(AnalysisError, match='both a time target and a controller'):
        forcing('', 'velocity_earth.x', variable=variable, controller=control)


def test_controller_only_columns_keep_existing_meanings_and_sensor_spelling():
    control = SimpleNamespace(signals={'V', 'A', 'B', 'UX'},
                              commands={'V':30, 'A':5, 'B':2, 'UX':-10}, outputs=[])
    f = forcing('time +V +A +B +UX\n0 1 2 3 4\n1 3 4 5 6', controller=control)
    assert f.values(.5) == {'V':32., 'A':8., 'B':6., 'UX':-5.}
    assert f.targets(.5) == {}
    assert all(item['group'] == 'commands' for item in f.channels)
    # Merely reading V is allowed if the forced inverse column has another owner.
    owned = forcing('time RX\n0 0\n1 1', 'position_earth.x', controller=control)
    assert owned.targets(.5) == {'position_earth.x': .5}
    with pytest.raises(ValueError, match='Unsupported'):
        forcing('time UX\n0 0\n1 1', 'velocity_earth.x')
    with pytest.raises(ValueError, match='Duplicate'):
        forcing('time A a\n0 0 0\n1 1 1', 'reference.alpha')


