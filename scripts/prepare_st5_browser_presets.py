"""Publish unchanged ST-5 inputs and their reviewed archived-station grids.

No solver, browser, build or pass-count update is performed. --check is read-only.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCOPE = ROOT / 'docs/validation/isae-st5-mechanics-scope.json'
SCOPE_SHA = 'b896edc1abfb8194cff98e6d3d3782dd7634e07e1ba17f92479d4046b48ad323'
PREFIX = '// Generated by scripts/prepare_st5_browser_presets.py; do not edit.\nexport const st5Examples = Object.freeze('
SUFFIX = ');\n'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def identity(case):
    if case.startswith('st5-forward-'):
        loading, weight = case.removeprefix('st5-forward-').split('_')
        return 'isae-' + case, f'ST-5 forward wing · {loading}, {weight[:-2]} lb'
    if case.startswith('st5-roller-'):
        name, label = case, 'type-2 roller'
    elif case.startswith('st5-elliptical-'):
        name, label = case, 'rigid joint · elliptical'
    else:
        name, label = case.replace('st5-', 'st5-static-', 1), 'rigid joint · cosine'
    weight, front, rear = name.rsplit('-', 1)[1].split('_')
    return 'isae-' + name, f'ST-5 {label} · {weight[:-2]} lb, {front}/{rear}'


def expected():
    assert sha(SCOPE) == SCOPE_SHA, 'Mechanics scope changed; review preset provenance.'
    scope = json.loads(SCOPE.read_text())
    catalog = ROOT / 'docs/validation/aswing-authoritative-sources.json'
    assert sha(catalog) == scope['authoritative_catalog_sha256']
    archive = ROOT / 'reference/isae-validation/f62943df20e9e4d7d9f50e070477b22426b5f865/3 - Structure/CASE - ST5 Joined Wing'
    originals = {}
    for path in sorted(archive.rglob('*.asw')):
        originals.setdefault(sha(path), []).append(str(path.relative_to(ROOT)))
    records, files = {}, {}
    provenance = {'scope': str(SCOPE.relative_to(ROOT)), 'scope_sha256': SCOPE_SHA, 'cases': []}
    for entry in scope['cases']:
        path = ROOT / entry['reference_plan']
        assert sha(path) == entry['reference_plan_sha256']
        plan = json.loads(path.read_text())
        source = ROOT / plan['source']
        assert sha(source) == plan['source_sha256']
        assert plan['source_sha256'] in originals, 'Example must equal an unchanged upstream model.'
        assert plan['request'] == {'action': 'solve', 'mode': 'structural'}
        target_path = ROOT / plan['target']
        assert sha(target_path) == plan['target_sha256']
        target = json.loads(target_path.read_text())
        for pin in target['source_pins']:
            assert sha(ROOT / pin['path']) == pin['sha256']
        mesh = plan['meshes'][0]
        assert mesh['level'] == 0
        for beam in target['beams']:
            expected_nodes = sorted({r['printed_t'] if r['exact_anchor_t'] is None
                                     else r['exact_anchor_t'] for r in beam['rows']})
            assert mesh['panels']['beams'][str(beam['beam'])]['nodes'] == expected_nodes
        key, label = identity(entry['case'])
        assert key not in records
        note = ('Literal ASWING type-2 roller. The report’s modified in-plane link is a separate setup.'
                if 'roller' in entry['case'] else 'Original static load case. Apply the comparison setup to select its reviewed equations and node grid.')
        records[key] = dict(case=entry['case'], label=label, note=note,
                            source_sha256=plan['source_sha256'], mesh=mesh['panels'])
        raw = source.read_bytes()
        for parent in ('examples', 'public/examples'):
            files[ROOT / parent / (key + '.asw')] = raw
        provenance['cases'].append(dict(case=entry['case'], key=key,
            reference_plan=entry['reference_plan'], reference_plan_sha256=entry['reference_plan_sha256'],
            source=str(source.relative_to(ROOT)), source_sha256=plan['source_sha256'],
            unchanged_upstream_sources=originals[plan['source_sha256']],
            target=str(target_path.relative_to(ROOT)), target_sha256=plan['target_sha256']))
    assert len(records) == 16
    files[ROOT / 'web/st5-baselines.js'] = (PREFIX + json.dumps(records, ensure_ascii=False, indent=2) + SUFFIX).encode()
    files[ROOT / 'docs/validation/isae-st5-browser-presets-sources.json'] = (json.dumps(provenance, indent=2) + '\n').encode()
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = expected()
    for path, content in files.items():
        if args.check:
            assert path.read_bytes() == content, str(path)
        elif path.suffix == '.asw' and path.exists():
            assert path.read_bytes() == content, 'Do not overwrite changed example: ' + str(path)
        else:
            path.write_bytes(content)
    print(json.dumps(dict(status='CURRENT' if args.check else 'PREPARED', cases=16,
                          files=len(files), solver_calls=0, primary_passes_added=0)))
